# Thesis fork: copies the result lines of the Simulator evaluation runs out of their logs
# (/private/tmp/oi-logs, cleared on restart) into the repository, one file a run, plus an index.
# Kept: per-case result rows and summary lines of the question sets, summaries, opinions, template
# routing, OCR and translation benchmarks, and the test outcome lines. Not kept: the logs' full
# answers, drafts and passages. EU holdout: only its model, import and SUMMARY/RESULT lines, never
# a question or an answer (AGENTS.md step 5).
#
# Usage: python3 collect_run_results.py [log-dir] [out-dir]
import datetime, os, re, sys

log_dir = sys.argv[1] if len(sys.argv) > 1 else "/private/tmp/oi-logs"
out_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "../../Docs/Thesis/experiments/runs")

KEEP = re.compile(
    r"^\[GreekEval\] (?:\||set=|model availability|imported|cleared|answer pass|right documents|summary set=)"
    r"|^\[GreekSummary\] (?:\||document|summary)"
    r"|^\[GreekOpinion\] (?:\||summary)"
    r"|^\[TemplateRouting\]"
    r"|^\[OCRBench\]"
    r"|^\[TranslateBench\]"
    r"|^\[ClaimCheckEvaluation\]"
    r"|^\[EUHoldout\] (?:model|imported|cleared|SUMMARY|RESULT)"
    r"|Test run with \d+ tests?|Executed \d+ tests?, with|^✘ Test \w+\("
    r"|failed to launch|Test runner hung|BUILD FAILED"
)
HEADLINE = re.compile(
    r"\[GreekEval\] summary set=|\[GreekSummary\] summary|\[GreekOpinion\] summary|\[EUHoldout\] RESULT"
    r"|\[TemplateRouting\] (?:summary|accuracy|split)|\[OCRBench\] SUMMARY|\[TranslateBench\]"
    r"|\[ClaimCheckEvaluation\] agrees|Test run with \d+ tests?|Executed \d+ tests?, with"
)

os.makedirs(out_dir, exist_ok=True)
index = []
for name in sorted(os.listdir(log_dir)):
    if not name.endswith(".log"):
        continue
    path = os.path.join(log_dir, name)
    kept, seen = [], set()
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.rstrip("\n")
            if KEEP.search(line) and line not in seen:
                seen.add(line)
                kept.append(line[:600])
    if not kept:
        continue
    run = name[:-4]
    when = datetime.datetime.fromtimestamp(os.path.getmtime(path)).strftime("%Y-%m-%d %H:%M")
    with open(os.path.join(out_dir, run + ".txt"), "w", encoding="utf-8") as f:
        f.write(f"# {run}: result lines of {name} (log last written {when})\n")
        f.write("\n".join(kept) + "\n")
    headlines = [l for l in kept if HEADLINE.search(l)]
    index.append((when, run, headlines[-3:]))

index.sort()
with open(os.path.join(out_dir, "INDEX.md"), "w", encoding="utf-8") as f:
    f.write("# Run index\n\nGenerated by `scripts/thesis/collect_run_results.py` from the Simulator logs. "
            "One file a run in this folder; the experiments and what each run tested are in "
            "`../../EXPERIMENTS.md` and `../../FORK_CHANGES.md`.\n\n| Finished | Run | Headline |\n|---|---|---|\n")
    for when, run, headlines in index:
        text = " · ".join(h.replace("|", "\\|").strip() for h in headlines) or "-"
        f.write(f"| {when} | [{run}]({run}.txt) | {text[:400]} |\n")
print(f"{len(index)} runs written to {out_dir}")
